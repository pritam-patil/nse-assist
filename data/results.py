"""RESULTS.md plumbing — every study owns one marker-delimited slice, only.

The log accumulates findings across bursts. Each study regenerates its own
section wholesale on every run and must leave every other byte of the file
alone; this module is the single implementation of that contract, so no study
grows its own slightly-different file surgery.
"""

from pathlib import Path

RESULTS_PATH = Path(__file__).resolve().parent.parent / "RESULTS.md"

PREAMBLE = (
    "# Results log\n\n"
    "Empirical findings from the dividend study, one marker-delimited section\n"
    "per burst, each regenerated by the script that owns it.\n\n"
)


def update(section, start_mark, end_mark, path=None):
    """Replaces the [start_mark, end_mark] slice, appends it if absent, creates
    the file with its preamble on first contact. Everything outside the marks is
    someone else's result and is preserved byte for byte."""
    path = Path(path or RESULTS_PATH)
    if path.exists():
        text = path.read_text()
        if start_mark in text and end_mark in text:
            before = text.split(start_mark)[0]
            after = text.split(end_mark, 1)[1]
            path.write_text(before + section + after)
            return path
        separator = "" if text.endswith("\n\n") else "\n"
        path.write_text(text + separator + section + "\n")
        return path
    path.write_text(PREAMBLE + section + "\n")
    return path
